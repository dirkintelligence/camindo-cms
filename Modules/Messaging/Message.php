<?php
/**
 * Dataset child class for the table `message` - CMS-internal messages between
 * backend users (admins).
 *
 * A message has exactly one recipient (to_admin_id) and one sender: that is
 * created_by, which Dataset::save() fills from the session when creating - so there is no
 * separate sender field. The date of the message is created_at.
 *
 * CONTENT
 * --------------------
 *     subject   subject, plain text
 *     body      message text, plain text (plaintext - prepared for display with
 *               htmlspecialchars/nl2br, never output as HTML)
 *     html      HTML code generated by the CMS, shown BELOW the text (optional;
 *               an editor cannot enter it, only forward it)
 *     record_id reference to a record: the message was written from its info page
 *               (RecordBackendInfo). Only the ID is stored;
 *               the teaser (Backend::teaser('record')) is created anew on each display
 *               and thus always shows the current title. FK ON DELETE SET NULL.
 *
 * body and html are of type 'encrypted' (Crypt::encrypt(), binary in mediumblob
 * columns): Dataset encrypts and decrypts them when saving and loading. They cannot
 * be searched as a result - the list shows and sorts only sender, date
 * and subject.
 *
 * READ
 * --------------------
 * is_read is not maintained via save() but via markRead(): opening a
 * message is no change of its content and should not touch changed_at/changed_by.
 * A change of recipient (hookOnSave) resets is_read - for the
 * new recipient the message is new. unreadCount() returns the number for the
 * badge in the backend header.
 *
 * IMPORTANT
 * --------------------
 * is_important is set by the recipient for themselves (markImportant()) - a warning symbol next to
 * the envelope in the list and detail view.
 *
 * TWO VIEWS, ONE ROW
 * --------------------
 * Inbox (to_admin_id) and outbox (created_by) show the same row.
 * If one side deletes, the other should keep its message (the sender should be able to
 * look up what they sent): deleteFor() therefore only sets
 * recipient_deleted resp. sender_deleted; only when both are set is the
 * row finally deleted - there is no trash (no `deleted` field).
 * A message to oneself has both roles - which one is meant is shown by the
 * list (box).
 *
 * Messages that the CMS sends itself (sendSystem(): result of a
 * batch processing) have only one view - the inbox of the addressee:
 * sender_deleted is set from the start, so they never appear in the outbox.
 *
 * RETENTION (GDPR)
 * --------------------
 * purgeExpired() permanently deletes messages privacy.message_days days (default 60) after
 * sending - from the scheduler task retention. deleteAllOf() clears the messages
 * of a user at once (superuser, settings of another user):
 * received ones completely, sent ones from their outbox - the recipients keep theirs.
 *
 * ACCESS
 * --------------------
 * Whoever is recipient or sender and has not deleted the message in
 * their view may see, change and delete it (canAccess()).
 *
 * @see Camindo\Core\Modules\Messaging\MessagingBackend  backend UI
 * @see Camindo\Core\Dataset
 */
namespace Camindo\Core\Modules\Messaging;

use Camindo\Core\Dataset;

class Message extends Dataset {

    // Audit log: private messages between admins are not logged
    protected bool $audit = false;

    protected function hookDefinition(): void
    {
        $this->tableName  = 'message';
        $this->moduleName = 'Messaging';
        $this->defaultSortOrder = 'created_at DESC';
        $this->defaultFieldName = 'subject';
        $this->schema = [
            'message_id' => [
                'type'  => 'integer',
                'label' => 'message_id',
                'min' => 1
            ],
            'to_admin_id' => [
                'type'  => 'id',
                'display_type' => 'lookup',
                'label' => '#messaging.field_message_to_admin_id',
                'table' => 'admin'
            ],
            'subject' => [
                'type'  => 'chars',
                'label' => '#messaging.field_message_subject',
                'max'   => 255,
                'flags' => ['trim', 'not_empty']
            ],
            'body' => [
                'type'  => 'encrypted',
                'display_type' => 'textarea',
                'label' => '#messaging.field_message_body',
                'flags' => ['trim', 'not_empty']
            ],
            'html' => [
                'type'  => 'encrypted',
                'display_type' => 'textarea',
                'label' => '#messaging.field_message_html',
            ],
            'record_id' => [
                'type'  => 'id',
                'label' => '#messaging.field_message_record_id',
                'table' => 'record'
            ],
            'is_read' => [
                'type'  => 'bit',
                'label' => '#messaging.field_message_is_read',
            ],
            'is_important' => [
                'type'  => 'bit',
                'label' => '#messaging.field_message_is_important',
            ],
            'recipient_deleted' => [
                'type'  => 'bit',
                'label' => '#messaging.field_message_recipient_deleted',
            ],
            'sender_deleted' => [
                'type'  => 'bit',
                'label' => '#messaging.field_message_sender_deleted',
            ],
            'created_by' => [
                'type'  => 'id',
                'label' => '#messaging.field_message_created_by',
                'table' => 'admin'
            ],
            'created_at' => [
                'type'  => 'timestampl',
                'label' => '#messaging.field_message_created_at',
                'default' => 'now'
            ],
            'changed_by' => [
                'type'  => 'id',
                'label' => '#messaging.field_message_changed_by',
                'table' => 'admin'
            ],
            'changed_at' => [
                'type'  => 'timestampl',
                'label' => '#messaging.field_message_changed_at',
                'default' => 'now'
            ],
        ];
    }

    /**
     * Before saving: the recipient must be an existing, not deleted admin.
     * A field of type 'id' does not run through the not_empty check (0 is there
     * a valid value and becomes NULL) - therefore done here.
     *
     * If the recipient changes, the message is unread for them.
     */
    protected function hookOnSave(array &$fields, array &$data, array &$previousData): void
    {
        if (!empty($fields) && !in_array('to_admin_id', $fields, true)) return;

        $toAdminId = (int)($data['to_admin_id'] ?? 0);
        $label = $this->schema['to_admin_id']['label'];
        if ($toAdminId < 1) {
            $this->createFieldError('error_value_mandatory', 'to_admin_id', $label);
            throw new \Exception('#' . $this->cms->errorMsgLast());
        }
        $this->db->pushResult();
        $this->db->query("SELECT 1 FROM `admin` WHERE `admin_id` = ? AND `deleted` = 0", 'i', [$toAdminId]);
        $found = $this->db->num_rows > 0;
        $this->db->popResult();
        if (!$found) {
            $this->createFieldError('messaging.error_recipient_unknown', 'to_admin_id', $label);
            throw new \Exception('#' . $this->cms->errorMsgLast());
        }

        if (!empty($previousData) && (int)($previousData['to_admin_id'] ?? 0) !== $toAdminId) {
            if (!in_array('is_read', $fields, true)) $fields[] = 'is_read';
            $data['is_read'] = 0;
        }
    }

    /**
     * May this admin see and edit the message? Recipient or sender.
     *
     * @param array $data     loaded message
     * @param int   $adminId  admin_id from the session
     */
    public function canAccess(array $data, int $adminId): bool
    {
        if ($adminId < 1) return false;
        $isRecipient = (int)($data['to_admin_id'] ?? 0) === $adminId && empty($data['recipient_deleted']);
        $isSender    = (int)($data['created_by'] ?? 0) === $adminId && empty($data['sender_deleted']);
        return $isRecipient || $isSender;
    }

    /**
     * Role of an admin with regard to the message - 'inbox' (recipient), 'outbox'
     * (sender) or ''. For a message to oneself, $box decides.
     *
     * @param array  $data     loaded message
     * @param int    $adminId  admin_id from the session
     * @param string $box      desired view ('inbox' | 'outbox' | '')
     */
    public function boxOf(array $data, int $adminId, string $box = ''): string
    {
        $isRecipient = (int)($data['to_admin_id'] ?? 0) === $adminId && empty($data['recipient_deleted']);
        $isSender    = (int)($data['created_by'] ?? 0) === $adminId && empty($data['sender_deleted']);
        if ($box === 'outbox' && $isSender) return 'outbox';
        if ($box === 'inbox' && $isRecipient) return 'inbox';
        if ($isRecipient) return 'inbox';
        if ($isSender) return 'outbox';
        return '';
    }

    /**
     * Delete a message from ONE view: set the flag of the role; if the
     * message is then gone for both sides, the soft delete follows.
     *
     * @param int    $id   message_id
     * @param string $box  'inbox' (as recipient) | 'outbox' (as sender)
     * @return bool        false: unknown view
     */
    public function deleteFor(int $id, string $box): bool
    {
        if ($id < 1 || !in_array($box, ['inbox', 'outbox'], true)) return false;
        $column = ($box === 'inbox') ? 'recipient_deleted' : 'sender_deleted';
        $this->db->pushResult();
        $this->db->query("UPDATE `message` SET `{$column}` = 1 WHERE `message_id` = ?", 'i', [$id]);
        $this->db->query(
            "SELECT `recipient_deleted` = 1 AND `sender_deleted` = 1 FROM `message` WHERE `message_id` = ?",
            'i', [$id]
        );
        $gone = (int)(($this->db->fetchNum() ?? [0])[0] ?? 0) === 1;
        $this->db->popResult();
        if ($gone) return $this->delete($id);   // final - no trash
        return true;
    }

    /**
     * Delete messages older than privacy.message_days (0 = never).
     * Directly via SQL: no audit log, no files, no trash (see above).
     *
     * @return int  deleted messages
     */
    public function purgeExpired(): int
    {
        $days = (int)($this->config->get('privacy.message_days') ?? 60);
        if ($days < 1) return 0;
        $this->db->pushResult();
        try {
            $this->db->query("DELETE FROM `message` WHERE `created_at` < DATE_SUB(UTC_TIMESTAMP(), INTERVAL ? DAY)", 'i', [$days]);
            return max(0, (int)$this->db->affected_rows);
        }
        finally {
            $this->db->popResult();
        }
    }

    /**
     * Number of messages of a user in their inbox and outbox.
     *
     * @return array  inbox, outbox
     */
    public function countOf(int $adminId): array
    {
        $this->db->pushResult();
        try {
            $this->db->query(
                "SELECT SUM(`to_admin_id` = ? AND `recipient_deleted` = 0), SUM(`created_by` = ? AND `sender_deleted` = 0)"
                . " FROM `message` WHERE `to_admin_id` = ? OR `created_by` = ?",
                'iiii', [$adminId, $adminId, $adminId, $adminId]
            );
            $row = $this->db->fetchNum() ?? [];
            return ['inbox' => (int)($row[0] ?? 0), 'outbox' => (int)($row[1] ?? 0)];
        }
        finally {
            $this->db->popResult();
        }
    }

    /**
     * Delete all messages of a user (superuser, e.g. for a locked-out
     * employee): received ones finally; sent ones disappear from their
     * outbox, the recipients keep their version - as with deleteFor('outbox').
     * If the recipient has already deleted it, the row is gone entirely.
     *
     * @return array  inbox (deleted received), outbox (removed sent)
     */
    public function deleteAllOf(int $adminId): array
    {
        if ($adminId < 1) return ['inbox' => 0, 'outbox' => 0];
        $this->db->pushResult();
        try {
            $this->db->query("DELETE FROM `message` WHERE `to_admin_id` = ?", 'i', [$adminId]);
            $inbox = max(0, (int)$this->db->affected_rows);
            $this->db->query("UPDATE `message` SET `sender_deleted` = 1 WHERE `created_by` = ? AND `sender_deleted` = 0", 'i', [$adminId]);
            $outbox = max(0, (int)$this->db->affected_rows);
            $this->db->query("DELETE FROM `message` WHERE `created_by` = ? AND `recipient_deleted` = 1", 'i', [$adminId]);
        }
        finally {
            $this->db->popResult();
        }
        return ['inbox' => $inbox, 'outbox' => $outbox];
    }

    /**
     * Message of the CMS to an admin (e.g. result of a batch processing):
     * visible only in the inbox of the addressee (see class comment). Sender
     * is the session admin (created_by) - in the background the trigger of the process.
     *
     * @return int|null  message_id or null on error (messages in Cms::errors)
     */
    public function sendSystem(int $toAdminId, string $subject, string $body, string $html = ''): ?int
    {
        // (save() takes $data by reference - an array literal would not work)
        $data = [
            'message_id'     => 0,
            'to_admin_id'    => $toAdminId,
            'subject'        => $subject,
            'body'           => $body,
            'html'           => $html,
            'sender_deleted' => 1,
        ];
        $id = $this->save(['to_admin_id', 'subject', 'body', 'html', 'sender_deleted'], $data);
        return $id ?: null;
    }

    /**
     * Set the important flag (recipient) - like markRead() without save().
     */
    public function markImportant(int $id, bool $important): void
    {
        if ($id < 1) return;
        $this->db->pushResult();
        $this->db->query(
            "UPDATE `message` SET `is_important` = ? WHERE `message_id` = ?",
            'ii', [$important ? 1 : 0, $id]
        );
        $this->db->popResult();
    }

    /**
     * Set the read flag - without save(), so that changed_at/changed_by
     * stay untouched (see class comment).
     *
     * @param int  $id    message_id
     * @param bool $read  true: read, false: unread
     */
    public function markRead(int $id, bool $read): void
    {
        if ($id < 1) return;
        $this->db->pushResult();
        $this->db->query(
            "UPDATE `message` SET `is_read` = ? WHERE `message_id` = ?",
            'ii',
            [$read ? 1 : 0, $id]
        );
        $this->db->popResult();
    }

    /**
     * Number of unread messages to an admin (badge in the backend header).
     *
     * @param int $adminId  admin_id
     */
    public function unreadCount(int $adminId): int
    {
        if ($adminId < 1) return 0;
        $this->db->pushResult();
        $this->db->query(
            "SELECT COUNT(*) FROM `message` WHERE `to_admin_id` = ? AND `is_read` = 0 AND `recipient_deleted` = 0",
            'i',
            [$adminId]
        );
        $count = (int)(($this->db->fetchNum() ?? [0])[0] ?? 0);
        $this->db->popResult();
        return $count;
    }
}

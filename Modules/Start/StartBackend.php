<?php
/**
 * Start page and login of the backend.
 *
 * Entry points (scripts in backend/):
 *
 *     start.php  -> start()   greeting and module overview
 *     login.php  -> login()   login dialog
 *     menu.php   -> menu()    content of the main menu (hamburger at top left): info,
 *                             manuals, the modules of the group
 *     info.php   -> info()    About camindo CMS: version; for superusers the result
 *                             of the update check (UpdateCheck) with "Check now"
 *
 * THE MODULE LIST DOES NOT COME FROM THE DATABASE
 * --------------------
 * _moduleButtons() runs over Cms::$modules - the file var/config/components/modules.php
 * generated by ComponentBackend. Only what has set 'listed' in its
 * install/settings.php is included; modules such as Area or Record appear
 * on the start page this way, helper modules do not.
 *
 * Each listed module must bring two things, which are assumed here:
 * the snippet {module}.module_label and the HTML template {module}.module_button.
 * A module that sets 'button' => false in settings.php stays without a tile despite 'listed' -
 * it remains subject to rights management but appears only as a
 * widget (as the module User does). Conversely, a module that is NOT listed but has
 * 'button' => true gets a tile for every group (as the trash, module Trash).
 *
 * FOUR SLOTS ON THE START PAGE
 * --------------------
 * The start page is a grid of four half-columns. Slot 1 (top left) is fixed
 * occupied by the module tiles; slots 2 to 4 are filled by each admin via their
 * personal settings with widgets of the modules (Camindo\Core\Widgets, where the
 * contract is stated). Several widgets fit into one slot; they stand there
 * one below the other, in the order in which they were added.
 * _startWidgets() only reads the setting and sets up the columns - what is shown
 * in the card is the responsibility of the respective module.
 *
 * THE LOGIN DIALOG IS A LAYER, NOT A PAGE
 * --------------------
 * login() does not output a complete document, but the three parts of a modal.
 * On success no HTML is sent at all, only JavaScript: the cookie is
 * set, cApp.layers.loginComplete() reloads the layers that were left empty and
 * closes the dialog. This keeps the state of the interface across the login -
 * one does not land on the start page, but where one was.
 *
 * TWO STAGES, ONE DIALOG
 * --------------------
 * If the admin has a second factor (e-mail per admin.2_factor, or an authenticator
 * app), Admin::loginByName() deliberately returns no 'sessid': no session has been
 * created yet - only a code has been sent by e-mail resp. the app
 * has been asked.
 * What distinguishes the two outputs of 'step1' is exactly this missing 'sessid' -
 * without it the second form follows, with it the login is complete.
 *
 * The second form carries the 'uid' from 'step1' on as a hidden field. It is
 * the only reference to the waiting account: the user name is not transmitted again,
 * and the code alone belongs to nobody. 'step2' passes both on to
 * Admin::loginByCode().
 *
 * Which code is expected is stated by 'factor' in the result (e-mail or authenticator
 * app, Admin::secondFactor()) - only the hint text depends on it. If TOTP is
 * mandatory (security.admin_2fa = totp_required) and still missing, the login returns
 * 'totp_setup' instead of the session: the dialog shows the QR code, 'totp_setup' checks
 * the first code (Admin::loginByTotpSetup()) and then shows the
 * recovery codes before it closes.
 *
 * PASSWORD MUST BE CHANGED
 * --------------------
 * If another admin has set the password, or it is older than
 * admin.password_retention_days, the login returns instead of the session
 * 'password_renew' (Admin::_loginComplete()): the dialog asks for a new password
 * ('password_change' -> Admin::loginByPasswordChange()). Only then does it continue,
 * if necessary with setting up TOTP. _loginNext() passes the results
 * of all stages on to the next step.
 *
 * ONE ATTEMPT PER CODE
 * --------------------
 * Admin::loginByCode() re-rolls the uid after each attempt, also after a failed one -
 * otherwise the code could be tried out at leisure. In addition, every wrong code counts
 * on the account in the LoginGuard (admin.bruteforce_max).
 * After a failed attempt there is therefore no way back to the code form: 'step2'
 * shows the empty login form again, and the user starts again from the beginning.
 *
 * LANGUAGE, LOCALE AND TIME ZONE ALREADY AT LOGIN
 * --------------------
 * The login form asks for backend language, locale (date and number format) and
 * time zone. They are preset by the JavaScript (cApp.ui.loginPrefsInit()): with
 * the last choice from localStorage - which AdminBackend::settings() also stores there -
 * otherwise with browser language, locale and time zone; a browser language without
 * backend translation ("nl") falls back to 'en_US' (Cms::resolveBackendLang()), a
 * locale without region or without ICU data to system.locale. The form itself is
 * already loaded in this language (Start/login.php?lang=…).
 *
 * After a successful login the choice lands as a personal setting in the
 * admin record (Admin::saveSettings()) - the same place that describes the settings
 * at the top right of the backend. In the two-factor login the three values travel as
 * hidden fields through the code form. In addition, the cookie of the frontend
 * editing is set according to the saved setting.
 *
 * OPERATIONAL WARNINGS UNDER THE MODULE TILES
 * --------------------
 * Superusers see under the module tiles what is not right in operation: cron job
 * missing, database backup missing or failed, disk almost full … (the
 * checks are in Camindo\Core\SystemHealth). Everything in order: no block.
 *
 * @see Camindo\Core\Widgets             widgets of the modules, slots 2 to 4
 * @see Camindo\Core\SystemHealth        operational warnings under the module tiles
 * @see Camindo\Core\Modules\Admin\Admin  loginByName(), the actual check
 * @see Camindo\Core\Session                session management
 * @see Camindo\Core\Modules\Start\StartBgproc  background process display in the header
 */
namespace Camindo\Core\Modules\Start;

use Camindo\Core\Backend;
use Camindo\Core\Cms;
use Camindo\Core\ComponentManager;
use Camindo\Core\FrontendHandover;
use Camindo\Core\AuditLog;
use Camindo\Core\Session;
use Camindo\Core\SystemHealth;
use Camindo\Core\UpdateCheck;
use Camindo\Core\Widgets;
use Camindo\Core\Modules\Admin\Admin;
use Camindo\Core\Modules\Record\Record;

class StartBackend {
    public function __construct(
        private Backend $backend,
        private Cms $cms,
        private Session $session,
        private Admin $admin,
        private Widgets $widgets,
        private Record $record,
        private SystemHealth $systemHealth,
        private AuditLog $auditLog,
        private UpdateCheck $updateCheck,
        private FrontendHandover $frontendHandover,
    )
    {}

    /**
     * Start page of the backend (backend/start.php).
     *
     * Greeting with the logged-in user and below it the buttons for the
     * available modules.
     */
    public function start(): void
    {
        // Header
        echo $this->backend->template('container_header');

        // Print login credentials
        echo $this->_loginCredentials();

        echo $this->backend->template('row_start');
        echo $this->backend->template('col_start_50');

        // H3 - "Available modules"
        echo $this->backend->template('headline2h3', [
            '{text}' => '{#start.headline_available_modules}'
        ]);

        // Module buttons
        echo $this->_moduleButtons();

        // Operational warnings (cron, backup, disk space …) - superusers only
        echo $this->_healthWarnings();

        echo $this->backend->template('col_end');

        // Slots 2 to 4: the widgets from the personal settings
        echo $this->_startWidgets();

        echo $this->backend->template('row_end');

        // Footer
        echo $this->backend->template('container_footer');
    }

    /**
     * Login dialog (backend/login.php).
     *
     * Three states:
     *     ''       show empty form
     *     'step1'  check name and password
     *     'step2'  check uid and code of the two-factor login
     *
     * On success no HTML is output, only the session cookie is set and
     * JavaScript is sent that lets the interface continue (see
     * class comment). On failure the form comes back with the error message -
     * which of the two inputs was wrong, Admin::loginByName() deliberately does not
     * reveal.
     * With the two-factor login, a new form for the code input appears.
     *
     * The entered name is masked with htmlspecialchars() when it is shown again
     * before it goes into the template.
     */
    public function login() {
        // Already logged in (e.g. in another window while the dialog was still open here):
        // do not log in again, but supply the token and
        // close the dialog (Backend::backendPath() lets this call through without a token)
        if ($this->session->load()) {
            $this->_loginResume();
            return;
        }

        // Page parameters
        $function = (string)($_POST['function'] ?? '');

        // Backend language, locale and time zone: from the form (step1) resp. the preset
        // (?lang=… from localStorage / browser, see class comment)
        $backendCode = $this->cms->resolveBackendLang((string)($_POST['backend_code'] ?? $_REQUEST['lang'] ?? ''));
        $timezone = trim((string)($_POST['timezone'] ?? ''));
        if (!$this->cms->isValidTimezone($timezone)) $timezone = $this->cms->serverTZ;
        $locale = trim((string)($_POST['locale'] ?? ''));
        if (!$this->cms->isValidLocale($locale)) $locale = $this->cms->userLocale;
        // The form in the chosen language
        $this->cms->setLang($backendCode);

        // Load modal templates
        // lang/dir: the page behind it was loaded without login in 'en_US' - the
        // dialog already stands in the chosen language and writing direction (Cms::isRtl())
        $tplHeader = $this->backend->template('start.modal_header', [
            '{camindo_cms}' => $this->backend->template('camindo_cms'),
            '{lang}' => htmlspecialchars(str_replace('_', '-', $backendCode), ENT_QUOTES),
            '{dir}' => $this->cms->textDirection($backendCode),
        ]);
        $tplForm = $this->backend->template('start.modal_form', $this->_loginFormOptions($backendCode, $timezone, $locale));
        $tplFormEmpty = str_replace('{name}', '', $tplForm);
        $tplFooter = $this->backend->template('start.modal_footer');
        // http:// with admin.cookie_secure = true: the browser discards the cookie -
        // note above the form instead of a login that mysteriously fails
        if ($this->session->secureCookieOverHttp()) {
            $tplHeader .= str_replace('{text}', $this->cms->snippet('start.warning_cookie_secure'),
                $this->backend->template('alert_warning'));
        }

        /**
         * Form 1
         */
        if ($function == '') {
            // Show form without messages
            echo $tplHeader;
            echo $tplFormEmpty;
            echo $tplFooter;
            // Preset language, locale and time zone (localStorage, otherwise browser)
            $this->backend->script('cApp.ui.loginPrefsInit();');
        }

        /**
         * Form 1 submitted
         */
        if ($function == 'step1') {
            // Form 1 submitted
            // Check name + password

            // Login attempt
            $name = $_REQUEST['name'] ?? '';
            $pass = $_REQUEST['pass'] ?? '';
            // 1. name and password empty

            // With active two-factor login, loginByName() sends an e-mail and
            // throws if that fails (no mailbox reachable, no MTA). Without this
            // catch the user would get a PHP error page in the dialog.
            try {
                $data = $this->admin->loginByName($name, $pass);
            } catch (\Throwable $e) {
                $this->_loginFailed(
                    $tplHeader, $tplForm, $tplFooter,
                    $this->cms->snippet('start.error_login_mail_failed'),
                    $name
                );
                return;
            }

            if ($data) {
                if (empty($data['sessid']) && empty($data['totp_setup']) && empty($data['password_renew'])) {
                    // Two-factor login: the code is on its way (e-mail) resp. in
                    // the app, but there is no session yet. Continue with form 2 -
                    // language and time zone travel along as hidden fields.
                    if (($data['factor'] ?? '') === 'webauthn') {
                        $this->_passkeyForm($tplHeader, $tplFooter, $data, $backendCode, $timezone, $locale);
                        return;
                    }
                    $totp = ($data['factor'] ?? '') === 'totp';
                    echo $tplHeader;
                    echo $this->backend->template('start.modal_form_code', [
                        '{text}' => $this->cms->snippet($totp ? 'start.text_login_code_totp' : 'start.text_login_code'),
                        // TOTP: also recovery codes (letters, XXXXX-XXXXX)
                        '{inputmode}' => $totp ? 'text' : 'numeric',
                        '{maxlength}' => $totp ? '16' : '5',
                        '{uid}' => htmlspecialchars((string)($data['uid'] ?? ''), ENT_QUOTES),
                        '{backend_code}' => htmlspecialchars($backendCode, ENT_QUOTES),
                        '{timezone}' => htmlspecialchars($timezone, ENT_QUOTES),
                        '{locale}' => htmlspecialchars($locale, ENT_QUOTES),
                    ]);
                    echo $tplFooter;
                    $this->backend->script("cApp.ui.focus('#login-code')");
                    return;
                }

                // Session, renew password or set up TOTP
                $this->_loginNext($data, $tplHeader, $tplFooter, $backendCode, $timezone, $locale);
            }
            else {
                // Error messages + form
                $this->_loginFailed($tplHeader, $tplForm, $tplFooter, $this->cms->errorMsg(), $name);
            }
        }

        /**
         * Form 2 submitted (two-factor login)
         */
        if ($function == 'step2') {
            // Check uid + code
            $uid  = (string)($_POST['uid'] ?? '');
            // Passkey: browser's response as JSON (cApp.ui.passkeyLogin()), otherwise code
            $code = (string)($_POST['passkey'] ?? '');
            if ($code === '') $code = (string)($_POST['code'] ?? '');

            if ($data = $this->admin->loginByCode($uid, $code)) {
                // Only now does a session exist (or password / TOTP follows)
                $this->_loginNext($data, $tplHeader, $tplFooter, $backendCode, $timezone, $locale);
            }
            else {
                // The uid is used up with this attempt (see class comment),
                // so a second code form would be useless. Back to form 1,
                // this time empty: the user name was only in form 1.
                $this->_loginFailed($tplHeader, $tplFormEmpty, $tplFooter, $this->cms->errorMsg(), '');
            }
        }

        /**
         * Mandatory TOTP setup submitted (security.admin_2fa = totp_required)
         */
        if ($function == 'totp_setup') {
            $uid   = (string)($_POST['uid'] ?? '');
            $token = (string)($_POST['token'] ?? '');
            $code  = (string)($_POST['code'] ?? '');
            $data = $this->admin->loginByTotpSetup($uid, $token, $code);

            if ($data && !empty($data['retry'])) {
                // Wrong code: the same QR code with a new uid; the failed attempt
                // counts in the LoginGuard (Admin::loginByTotpSetup())
                $this->auditLog->login('login_failed', 0, '');
                $alert = str_replace('{text}', $this->cms->errorMsg(), $this->backend->template('alert_danger'));
                $this->_totpSetupForm($tplHeader . $alert, $tplFooter, $data, $backendCode, $timezone, $locale);
            }
            elseif ($data && !empty($data['sessid'])) {
                $this->_loginNext($data, $tplHeader, $tplFooter, $backendCode, $timezone, $locale);
            }
            else {
                $this->_loginFailed($tplHeader, $tplFormEmpty, $tplFooter, $this->cms->errorMsg(), '');
            }
        }

        /**
         * New password submitted (initial password, expired)
         */
        if ($function == 'password_change') {
            $uid = (string)($_POST['uid'] ?? '');
            $data = $this->admin->loginByPasswordChange($uid,
                (string)($_POST['password'] ?? ''), (string)($_POST['password_repeat'] ?? ''));

            if ($data && !empty($data['retry'])) {
                // Password rejected (policy, repetition, unchanged): the same
                // form with a new uid
                $alert = str_replace('{text}', $this->cms->errorMsg(), $this->backend->template('alert_danger'));
                $this->_passwordChangeForm($tplHeader . $alert, $tplFooter, $data, $backendCode, $timezone, $locale);
            }
            elseif ($data) {
                $this->_loginNext($data, $tplHeader, $tplFooter, $backendCode, $timezone, $locale);
            }
            else {
                $this->_loginFailed($tplHeader, $tplFormEmpty, $tplFooter, $this->cms->errorMsg(), '');
            }
        }
    }

    /**
     * Next step after a successful login stage (see class comment):
     * new password, set up TOTP or - with 'sessid' - done.
     *
     * @param array $data  result of Admin::loginBy…()
     */
    private function _loginNext(array $data, string $tplHeader, string $tplFooter,
        string $backendCode, string $timezone, string $locale): void
    {
        if (!empty($data['password_renew'])) {
            $this->_passwordChangeForm($tplHeader, $tplFooter, $data, $backendCode, $timezone, $locale);
            return;
        }
        if (!empty($data['totp_setup'])) {
            $this->_totpSetupForm($tplHeader, $tplFooter, $data, $backendCode, $timezone, $locale);
            return;
        }
        // Set session cookie (HttpOnly, secure/SameSite from the configuration)
        $this->session->setCookie((string)$data['sessid']);
        $this->_loginComplete((int)$data['admin_id'], $backendCode, $timezone, $locale,
            (array)($data['recovery_codes'] ?? []), $tplHeader, $tplFooter);
    }

    /**
     * Second stage with passkey (WebAuthnFactor): button "Confirm with passkey" -
     * the script fetches the signature from the device and sends it in the field 'passkey' -,
     * below it the field for the app code (if TOTP is active) resp.
     * recovery code. Without options (WebAuthn not available, no passkeys
     * any more) only the code field.
     */
    private function _passkeyForm(string $tplHeader, string $tplFooter, array $data,
        string $backendCode, string $timezone, string $locale): void
    {
        $options = $data['webauthn'] ?? null;
        $totp = !empty($data['totp_active']);
        echo $tplHeader;
        echo $this->backend->template('start.modal_form_passkey', [
            '{text}' => $this->cms->snippet(is_array($options) ? 'start.text_login_passkey' : 'start.text_login_passkey_unavailable'),
            '{passkey_block}' => is_array($options) ? $this->backend->template('start.modal_passkey_button', [
                '{options}' => htmlspecialchars(json_encode($options, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE), ENT_QUOTES),
            ]) : '',
            '{code_label}' => $this->cms->snippet($totp ? 'start.label_login_code_totp_or_recovery' : 'start.label_login_recovery_code'),
            '{uid}' => htmlspecialchars((string)($data['uid'] ?? ''), ENT_QUOTES),
            '{backend_code}' => htmlspecialchars($backendCode, ENT_QUOTES),
            '{timezone}' => htmlspecialchars($timezone, ENT_QUOTES),
            '{locale}' => htmlspecialchars($locale, ENT_QUOTES),
        ]);
        echo $tplFooter;
        $this->backend->script(is_array($options) ? "cApp.ui.focus('#login-passkey')" : "cApp.ui.focus('#login-code')");
    }

    /**
     * New password in the login dialog: reason (initial password / expired), two
     * fields; the first with the Password extension (strength, requirements - as in
     * the input mask of the admin). The uid travels as a hidden field.
     */
    private function _passwordChangeForm(string $tplHeader, string $tplFooter, array $data,
        string $backendCode, string $timezone, string $locale): void
    {
        $extClass = '';
        $extAttr = '';
        $ext = $this->backend->fieldExtension($this->admin->getSchema()['password'] ?? []);
        if ($ext !== null) {
            $extClass = ' c9-ext';
            $extAttr = ' data-c9-ext="' . htmlspecialchars($ext['name']) . '" data-c9-ext-type="password"'
                . " data-c9-ext-options='" . htmlspecialchars(json_encode($ext['options'], JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE), ENT_QUOTES) . "'";
        }
        $reason = (string)$data['password_renew'] === 'expired' ? 'expired' : 'initial';
        echo $tplHeader;
        echo $this->backend->template('start.modal_form_password_change', [
            '{text}' => $this->cms->snippet('start.text_password_change_' . $reason),
            '{ext_class}' => $extClass,
            '{ext_attr}' => $extAttr,
            '{uid}' => htmlspecialchars((string)($data['uid'] ?? ''), ENT_QUOTES),
            '{backend_code}' => htmlspecialchars($backendCode, ENT_QUOTES),
            '{timezone}' => htmlspecialchars($timezone, ENT_QUOTES),
            '{locale}' => htmlspecialchars($locale, ENT_QUOTES),
        ]);
        echo $tplFooter;
        $this->backend->script("cApp.extensions && cApp.extensions.refreshAll($('#login-dialog')); cApp.ui.focus('#login-new-password')");
    }

    /**
     * Set up TOTP in the login dialog: QR code, secret to type in, code field.
     * The setup token (encrypted secret, TotpFactor::newSetup()) and the uid
     * travel as hidden fields - nothing is saved yet.
     *
     * @param array $data  result of Admin::loginByName()/loginByCode()/loginByTotpSetup()
     *                     with 'uid' and 'totp_setup'
     */
    private function _totpSetupForm(string $tplHeader, string $tplFooter, array $data,
        string $backendCode, string $timezone, string $locale): void
    {
        $setup = (array)$data['totp_setup'];
        echo $tplHeader;
        echo $this->backend->template('start.modal_form_totp_setup', [
            '{uri}' => htmlspecialchars((string)$setup['uri'], ENT_QUOTES),
            '{secret}' => htmlspecialchars((string)$setup['secret'], ENT_QUOTES),
            '{token}' => htmlspecialchars((string)$setup['token'], ENT_QUOTES),
            '{uid}' => htmlspecialchars((string)($data['uid'] ?? ''), ENT_QUOTES),
            '{backend_code}' => htmlspecialchars($backendCode, ENT_QUOTES),
            '{timezone}' => htmlspecialchars($timezone, ENT_QUOTES),
            '{locale}' => htmlspecialchars($locale, ENT_QUOTES),
        ]);
        echo $tplFooter;
        $this->backend->script("cApp.ui.qrCodes(); cApp.ui.focus('#login-code')");
    }

    /**
     * Logout (backend/logout.php).
     *
     * Two states:
     *     ''         show confirmation "Really log out?" as a modal
     *     'confirm'  log out
     */
    public function logout(): void
    {
        // Page parameters
        $function = (string)($_POST['function'] ?? '');

        if ($function === 'confirm') $this->_logout();
        else $this->_logoutForm();
    }

    /**
     * Confirmation before logging out.
     *
     * Output - as with login - are the parts of a modal that the
     * JavaScript (cApp.layers.logout()) loads into the same dialog (#login-modal).
     * The form sends itself back to this script with 'confirm'; the
     * cancel button closes the modal (data-bs-dismiss) and leaves the
     * interface untouched.
     */
    private function _logoutForm(): void
    {
        echo $this->backend->template('start.modal_logout_header');
        echo $this->backend->template('start.modal_logout_form');
        echo $this->backend->template('start.modal_footer');
    }

    /**
     * Perform logout.
     *
     * Before the session is closed, the working copies are discarded - this releases
     * the edit locks. Afterwards the session admin ID would be missing, against which
     * Record::cancel() checks ownership.
     *
     *     without checkmark     only this browser: the working copies of THIS session
     *                           (Record::cancelSession()); open masks on other
     *                           devices remain
     *     "on all devices"      all working copies of the admin (Record::cancelAll())
     *                           and all of their sessions (Session::closeAllOf())
     *
     * Unsaved inputs in the affected masks are thereby lost; the automatic logout
     * after admin.max_inactive_sec does not run through here
     * and leaves the copies in place (their lock expires after the same time).
     */
    private function _logout(): void
    {
        $adminId = (int)$this->session->get('admin_id');
        $allDevices = !empty($_POST['all_devices']);

        // Release edit locks
        if ($allDevices) {
            $this->record->cancelAll();
        }
        else {
            $this->record->cancelSession((string)$this->session->get('session_id'));
        }

        // Audit log - as long as the session still knows the admin
        $this->auditLog->login('logout', $adminId);

        // Delete sessions from the database (the others first: close() unloads the rights)
        if ($allDevices) {
            $this->session->closeAllOf($adminId, keepCurrent: true);
        }
        $this->session->close();

        // Frontend editing "until logout" (cookie 'fed' = 1) ends here;
        // 2 (permanent) remains - see Backend::setFedCookie()
        if ($this->frontendHandover->fedMode((string)($_COOKIE[$this->cms::FED_COOKIE] ?? '')) === 1) {
            $this->backend->setFedCookie(0);
        }

        // Reload the complete window
        $this->backend->script("window.location.href='/backend/index.php';");
    }

    /**
     * Login dialog when a session already exists (login()): supply the CSRF token of the
     * session, reload layers, close the dialog - like after a
     * login, but without saving settings or writing to the audit log.
     * Language and locale from the saved settings.
     */
    private function _loginResume(): void
    {
        $settings = $this->backend->adminSettings();
        $code = json_encode((string)($settings['backend_code'] ?? ''));
        $loc = json_encode((string)($settings['locale'] ?? ''));
        $token = json_encode($this->session->csrfToken());
        $this->backend->script("cApp.system.setCsrfToken({$token}); cApp.layers.loginComplete({$code}, {$loc});");
    }

    /**
     * Login completed: save the choice of language, locale and time zone as a personal
     * setting, set the frontend editing cookie, and let the interface continue
     * running.
     *
     * Saving must not make the login fail - if it does, the previous setting remains.
     * The session has already been updated by Admin::hookOnSaved(), so the new language
     * applies from the next request; the JavaScript reloads the backend if the header
     * is still in another language
     * (cApp.layers.loginComplete()).
     *
     * @param int    $adminId
     * @param string $backendCode  chosen backend language (already resolved)
     * @param string $timezone     chosen time zone (already checked)
     * @param string $locale       chosen locale (already checked)
     * @param array  $recoveryCodes  after the mandatory TOTP setup: the
     *                               recovery codes - the dialog shows them
     *                               and only closes with "Next"
     */
    private function _loginComplete(int $adminId, string $backendCode, string $timezone, string $locale,
        array $recoveryCodes = [], string $tplHeader = '', string $tplFooter = ''): void
    {
        $this->admin->saveSettings($adminId, [
            'backend_code' => $backendCode,
            'timezone'     => $timezone,
            'locale'       => $locale,
        ]);
        $this->cms->errorsReset();
        $this->auditLog->login('login', $adminId);

        // Frontend editing per saved setting (cookie of this browser)
        $settings = $this->backend->adminSettings();
        $this->backend->setFedCookie((int)($settings['fed'] ?? 0));

        // JavaScript output: supply the CSRF token of the new session, remember the choice
        // for the next login form, reload contents of layers that remained empty, and
        // close the login dialog.
        //
        // The token MUST come first: the page was loaded without a session, so cConfig still
        // holds an empty token - and the layers that are reloaded right after should already
        // send the new one along (developer docs, chapter 14 (Security: web)).
        $code = json_encode($backendCode);
        $tz = json_encode($timezone);
        $loc = json_encode($locale);
        $token = json_encode($this->session->csrfToken());
        $complete = "cApp.ui.loginPrefsStore({$code}, {$tz}, {$loc}); cApp.layers.loginComplete({$code}, {$loc});";

        if ($recoveryCodes) {
            // Show codes; continue only with the button
            echo $tplHeader;
            echo $this->backend->template('start.modal_recovery_codes', [
                '{codes}' => $this->_recoveryCodesHtml($recoveryCodes),
                '{onclick}' => $this->backend->on('click', $complete),
            ]);
            echo $tplFooter;
            $this->backend->script("cApp.system.setCsrfToken({$token});");
            return;
        }
        $this->backend->script("cApp.system.setCsrfToken({$token}); " . $complete);
    }

    /**
     * List of recovery codes with copy button (template as in the personal
     * settings, AdminBackend::totp()).
     */
    private function _recoveryCodesHtml(array $codes): string
    {
        $items = '';
        foreach ($codes as $code) {
            $items .= '<li>' . htmlspecialchars((string)$code) . "</li>\n";
